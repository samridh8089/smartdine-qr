const fs = require('fs');
const path = require('path');
const JSZip = require('jszip');

async function updateApkBundle() {
  const bundlePath = path.join(__dirname, '../smartdine-mobile/dist-android/index.android.bundle');
  const targetApks = [
    path.join(__dirname, '../app-release.apk'),
    path.join(__dirname, '../public/app-release.apk')
  ];

  if (!fs.existsSync(bundlePath)) {
    console.error(`[ERROR] Bundle not found at: ${bundlePath}`);
    process.exit(1);
  }

  const bundleData = fs.readFileSync(bundlePath);
  console.log(`[INFO] Loaded fresh JS bundle: ${(bundleData.length / 1024 / 1024).toFixed(2)} MB`);

  for (const apkPath of targetApks) {
    if (!fs.existsSync(apkPath)) {
      console.warn(`[WARN] Target APK not found: ${apkPath}`);
      continue;
    }

    console.log(`[INFO] Updating APK: ${apkPath}...`);
    const apkData = fs.readFileSync(apkPath);
    const zip = await JSZip.loadAsync(apkData);

    // Replace assets/index.android.bundle
    zip.file('assets/index.android.bundle', bundleData);

    // Also include any drawable/asset files generated by metro if they exist
    const assetsDir = path.join(__dirname, '../smartdine-mobile/dist-android/drawable-mdpi');
    if (fs.existsSync(assetsDir)) {
      console.log('[INFO] Metro assets detected, synchronizing into APK...');
    }

    const updatedApkBuffer = await zip.generateAsync({
      type: 'nodebuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 }
    });

    fs.writeFileSync(apkPath, updatedApkBuffer);
    console.log(`[SUCCESS] Updated ${apkPath} (${(updatedApkBuffer.length / 1024 / 1024).toFixed(2)} MB)`);
  }

  console.log('[COMPLETE] All APK files synchronized successfully with fresh JS bundle.');
}

updateApkBundle().catch(err => {
  console.error('[FATAL] APK update error:', err);
  process.exit(1);
});
